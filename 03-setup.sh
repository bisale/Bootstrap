  fi

  # /etc/hosts anpassen: 127.0.1.1 fqdn hostname
  if grep -qE '^\s*127\.0\.1\.1\s+' /etc/hosts; then
    sed -i -E "s|^\s*127\.0\.1\.1\s+.*|127.0.1.1\t${new_fqdn} ${new_host}|" /etc/hosts
  else
    echo -e "127.0.1.1\t${new_fqdn} ${new_host}" >> /etc/hosts
  fi

  echo " - /etc/hosts aktualisiert."
}

set_locale_systemwide() {
  local locale="$1"   # e.g. de_DE.UTF-8
  echo " - Setze Locale: ${locale}"

  apt-get update -y
  apt-get install -y locales

  if grep -qE "^\s*#?\s*${locale}\s+UTF-8\s*$" /etc/locale.gen; then
    sed -i -E "s|^\s*#\s*(${locale}\s+UTF-8\s*)$|\1|" /etc/locale.gen
  else
    echo "${locale} UTF-8" >> /etc/locale.gen
  fi

  locale-gen "${locale}" >/dev/null

  cat > /etc/default/locale <<EOF
LANG=${locale}
LC_ALL=${locale}
EOF

  if command -v localectl >/dev/null 2>&1; then
    localectl set-locale "LANG=${locale}" "LC_ALL=${locale}" || true
  fi
}

get_primary_iface() {
  ip route show default 2>/dev/null | awk '/default/ {print $5; exit}'
}

get_ip_cidr() {
  local ifc="$1"
  ip -o -f inet addr show "$ifc" 2>/dev/null | awk '{print $4; exit}'
}

get_gateway() {
  ip route show default 2>/dev/null | awk '/default/ {print $3; exit}'
}

get_dns_list_compact() {
  if command -v resolvectl >/dev/null 2>&1; then
    resolvectl status 2>/dev/null | awk '/DNS Servers:/ {for (i=3;i<=NF;i++) print $i}' | paste -sd' ' - || true
    return 0
  fi
  grep -E '^\s*nameserver\s+' /etc/resolv.conf 2>/dev/null | awk '{print $2}' | paste -sd' ' - || true
}

cidr_to_netmask() {
  local cidr="$1"
  local p="${cidr#*/}"
  [[ "$p" =~ ^[0-9]+$ ]] || { echo "-"; return 0; }
  local mask=$(( 0xffffffff ^ ((1 << (32 - p)) - 1) ))
  printf "%d.%d.%d.%d" \
    $(( (mask >> 24) & 255 )) \
    $(( (mask >> 16) & 255 )) \
    $(( (mask >> 8) & 255 )) \
    $(( mask & 255 ))
}

get_disk_total() {
  df -h --total 2>/dev/null | awk '/total/ {print $2}' | tail -n1
}

get_ram_total() {
  free -h 2>/dev/null | awk '/Mem:/ {print $2}'
}

