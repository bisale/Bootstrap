# ---------- Helper ----------
yesno() {
  local prompt="$1"
  local def="${2:-n}"
  local ans

  if [[ "$def" == "y" ]]; then
    read -rp "${prompt} (Y/n): " ans
    ans="${ans,,}"
    [[ -z "$ans" ]] && ans="y"
  else
    read -rp "${prompt} (y/N): " ans
    ans="${ans,,}"
    [[ -z "$ans" ]] && ans="n"
  fi

  [[ "$ans" == "y" || "$ans" == "yes" ]]
}

normalize_fpr() {
  tr -d '[:space:]' | tr '[:lower:]' '[:upper:]'
}

verify_gpg_fingerprint() {
  local key_file="$1"
  local expected="$2"
  local actual=""

  actual="$(gpg --show-keys --with-colons --fingerprint "$key_file" 2>/dev/null \
    | awk -F: '$1 == "fpr" {print $10; exit}' \
    | normalize_fpr)"

  expected="$(printf '%s' "$expected" | normalize_fpr)"

  if [[ -z "$actual" ]]; then
    echo "Fehler: Fingerprint konnte nicht aus ${key_file} gelesen werden."
    return 1
  fi

  if [[ "$actual" != "$expected" ]]; then
    echo "Fehler: GPG-Key-Fingerprint stimmt nicht."
    echo "Erwartet: $expected"
    echo "Gefunden : $actual"
    return 1
  fi

  echo " - Fingerprint OK: $actual"
}

get_current_dns() {
  if command -v resolvectl >/dev/null 2>&1; then
    resolvectl status 2>/dev/null | awk '
      /Current DNS Server:/ {print $0}
      /DNS Servers:/ {print $0}
    ' | sed 's/^[[:space:]]*//'
    return 0
  fi

  if [[ -f /etc/resolv.conf ]]; then
    grep -E '^\s*nameserver\s+' /etc/resolv.conf || true
    return 0
  fi

  echo "Konnte DNS nicht ermitteln."
}

set_dns_systemwide() {
  local dns_list="$1"

  if [[ -d /run/systemd/resolve || -f /lib/systemd/system/systemd-resolved.service || -f /usr/lib/systemd/system/systemd-resolved.service ]]; then
    echo " - Verwende systemd-resolved: /etc/systemd/resolved.conf"
    local conf="/etc/systemd/resolved.conf"

    mkdir -p /etc/systemd
    cp -a "$conf" "${conf}.bak.$(date +%Y%m%d-%H%M%S)" 2>/dev/null || true

    if [[ -f "$conf" ]] && grep -qE '^[#[:space:]]*DNS=' "$conf"; then
      sed -i -E "s|^[#[:space:]]*DNS=.*|DNS=${dns_list}|" "$conf"
    else
      if [[ ! -f "$conf" ]] || ! grep -qE '^\[Resolve\]' "$conf"; then
        printf "[Resolve]\n" > "$conf"
      fi
      echo "DNS=${dns_list}" >> "$conf"
    fi

    if command -v systemctl >/dev/null 2>&1; then
      systemctl restart systemd-resolved || true
    fi

    if [[ -e /run/systemd/resolve/stub-resolv.conf ]]; then
      if [[ -f /etc/resolv.conf && ! -L /etc/resolv.conf ]]; then
        cp -a /etc/resolv.conf "/etc/resolv.conf.bak.$(date +%Y%m%d-%H%M%S)" || true
        rm -f /etc/resolv.conf
      fi
      ln -sf /run/systemd/resolve/stub-resolv.conf /etc/resolv.conf
    fi

    echo " - DNS gesetzt via systemd-resolved."
    return 0
  fi

  if [[ -d /etc/dhcp ]]; then
    local dhconf="/etc/dhcp/dhclient.conf"
    cp -a "$dhconf" "${dhconf}.bak.$(date +%Y%m%d-%H%M%S)" 2>/dev/null || true

    local dns_csv
    dns_csv="$(echo "$dns_list" | tr ' ' ',')"

    local line="supersede domain-name-servers ${dns_csv};"
    if [[ -f "$dhconf" ]] && grep -qE '^\s*supersede\s+domain-name-servers' "$dhconf"; then
      sed -i -E "s|^\s*supersede\s+domain-name-servers.*;|${line}|" "$dhconf"
    else
      echo "" >> "$dhconf"
      echo "# set by bootstrap script" >> "$dhconf"
      echo "$line" >> "$dhconf"
    fi
    echo " - dhclient.conf angepasst: $line"
  else
    echo " - /etc/dhcp nicht vorhanden, DHCP-supersede nicht gesetzt."
  fi

  {
    echo "# generated by bootstrap script"
    for ns in $dns_list; do
      echo "nameserver $ns"
    done
  } > /etc/resolv.conf

  echo " - /etc/resolv.conf geschrieben (Fallback)."
}

set_hostname_fqdn_systemwide() {
  local new_fqdn="$1"
  local new_host
  new_host="${new_fqdn%%.*}"

  echo " - Setze Hostname: ${new_host}"
  echo "${new_host}" > /etc/hostname

  if command -v hostnamectl >/dev/null 2>&1; then
    hostnamectl set-hostname "${new_fqdn}" || hostnamectl set-hostname "${new_host}" || true
  else
    hostname "${new_host}" || true
  fi

  if grep -qE '^\s*127\.0\.1\.1\s+' /etc/hosts; then
    sed -i -E "s|^\s*127\.0\.1\.1\s+.*|127.0.1.1\t${new_fqdn} ${new_host}|" /etc/hosts
  else
    echo -e "127.0.1.1\t${new_fqdn} ${new_host}" >> /etc/hosts
  fi

  echo " - /etc/hosts aktualisiert."
}

set_locale_systemwide() {
  local locale="$1"

  echo " - Setze Locale: ${locale}"
  apt-get update -y
  apt-get install -y locales

  if grep -qE "^\s*#?\s*${locale}\s+UTF-8\s*$" /etc/locale.gen; then
    sed -i -E "s|^\s*#\s*(${locale}\s+UTF-8\s*)$|\1|" /etc/locale.gen
  else
    echo "${locale} UTF-8" >> /etc/locale.gen
  fi

  locale-gen "${locale}" >/dev/null

  cat > /etc/default/locale <<EOF
LANG=${locale}
LC_ALL=${locale}
EOF

  if command -v localectl >/dev/null 2>&1; then
    localectl set-locale "LANG=${locale}" "LC_ALL=${locale}" || true
  fi
}

