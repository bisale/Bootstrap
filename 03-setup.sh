get_dns_list_compact() {
  if command -v resolvectl >/dev/null 2>&1; then
    resolvectl status 2>/dev/null | awk '/DNS Servers:/ {for (i=3;i<=NF;i++) print $i}' | paste -sd' ' - || true
    return 0
  fi

  grep -E '^\s*nameserver\s+' /etc/resolv.conf 2>/dev/null | awk '{print $2}' | paste -sd' ' - || true
}

cidr_to_netmask() {
  local cidr="$1"
  local p="${cidr#*/}"

  [[ "$p" =~ ^[0-9]+$ ]] || { echo "-"; return 0; }

  local mask=$(( 0xffffffff ^ ((1 << (32 - p)) - 1) ))
  printf "%d.%d.%d.%d" \
    $(( (mask >> 24) & 255 )) \
    $(( (mask >> 16) & 255 )) \
    $(( (mask >> 8) & 255 )) \
    $(( mask & 255 ))
}

